#!/usr/bin/env node
/**
 * Generate src/inference/languages.ts — the picker's catalogue of every language the phonemizer
 * routes.
 *
 * Sources, all of them checked in so a rebuild is reproducible:
 *   tools/data/language-meta.json  names, sample sentences, voice fallbacks (hand-editable)
 *   tools/data/lang-dirs.json      per-language data size, from stage-phonemizer-data.mjs
 *   public/models/voices.jsonc     which languages have a reference voice of their own
 *
 * ⚠ A language is offered whether or not it has a NATIVE voice, because cloning is always on and a
 * reference is mandatory (short input without one can emit noise, not degrade). Where FLEURS has no
 * speaker, `voice` names a donor language chosen for phonetic/areal proximity — a Faroese sentence
 * read by an Icelandic voice, Sesotho by a Sepedi one. That is audible and the UI says so; it is
 * still far better than an English voice reading everything, because cloning copies accent.
 */
import { readFileSync, writeFileSync } from "node:fs";

const meta = JSON.parse(readFileSync("tools/data/language-meta.json", "utf8"));
const dirs = JSON.parse(readFileSync("tools/data/lang-dirs.json", "utf8"));

const voicesText = readFileSync("public/models/voices.jsonc", "utf8");
const strip = (t) => {
  let out = "", inStr = false, esc = false, line = false, block = false;
  for (let i = 0; i < t.length; i++) {
    const c = t[i], n = t[i + 1];
    if (line) { if (c === "\n") { line = false; out += c; } continue; }
    if (block) { if (c === "*" && n === "/") { block = false; i++; } continue; }
    if (inStr) { out += c; if (esc) esc = false; else if (c === "\\") esc = true; else if (c === '"') inStr = false; continue; }
    if (c === '"') { inStr = true; out += c; continue; }
    if (c === "/" && n === "/") { line = true; i++; continue; }
    if (c === "/" && n === "*") { block = true; i++; continue; }
    out += c;
  }
  return out;
};
const nativeVoice = new Set(JSON.parse(strip(voicesText)).map((v) => v.lang));

/** The v6 fine-tune's coverage set (Vernacula.Tts.CLI/IpaFineTune.cs). Everything else renders from
 *  phones the model already holds — the premise of an IPA-conditioned model — but is extrapolated. */
const TRAINED = new Set(["en", "cmn", "hi", "es", "ar", "fr", "pt", "ru", "de", "ja", "tr", "vi",
  "ta", "ko", "ha", "th", "am", "om", "sd", "ff", "kk", "zu", "cs", "sv", "xh", "ca", "ga", "cy"]);

const rows = Object.entries(meta)
  .map(([code, m]) => {
    const voice = nativeVoice.has(code) ? undefined : m.voice;
    if (!nativeVoice.has(code) && !voice)
      throw new Error(`${code} has neither a native voice nor a donor in language-meta.json`);
    return {
      code, name: m.name,
      mb: Math.round(((dirs[code]?.bytes ?? 0) / 1e6) * 100) / 100,
      sample: m.sample,
      voice,
      trained: TRAINED.has(code) || undefined,
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name, "en"));

const lit = (v) => JSON.stringify(v);
const body = rows.map((r) => {
  const f = [`code: ${lit(r.code)}`, `name: ${lit(r.name)}`, `mb: ${r.mb}`];
  if (r.trained) f.push("trained: true");
  if (r.voice) f.push(`voice: ${lit(r.voice)}`);
  if (r.sample) f.push(`sample: ${lit(r.sample)}`);
  return `  { ${f.join(", ")} },`;
}).join("\n");

const out = `// GENERATED by tools/make-language-catalog.mjs — do not edit.
// Edit tools/data/language-meta.json (names, samples, voice donors) and re-run:
//   node tools/stage-phonemizer-data.mjs && node tools/make-language-catalog.mjs

/** One row of the language picker. */
export interface LanguageOption {
  /** vernacula-phonemizer language code. */
  code: string;
  name: string;
  /** Phoneme-table download for this language, in MB, on top of the 4.5 MB engine set. */
  mb: number;
  /** In the v6 fine-tune's coverage set. Everything else renders, but extrapolated. */
  trained?: boolean;
  /** Donor language for the reference voice — absent when the language has a native one. */
  voice?: string;
  /** Prefilled example text. Absent where no verified sentence was available. */
  sample?: string;
}

/** Every language the phonemizer can route, alphabetically by name. */
export const LANGUAGES: LanguageOption[] = [
${body}
];

export const LANGUAGE_BY_CODE = new Map(LANGUAGES.map((l) => [l.code, l]));

/** Which language's REFERENCE VOICE renders this one — itself, or its donor.
 *
 *  ⚠ Cloning is acoustic: the reference carries the speaker's accent as well as their timbre, so a
 *  donor is always a near neighbour (Faroese read by Icelandic, Sesotho by Sepedi, Hakka by
 *  Cantonese) rather than a default English voice. */
export function voiceLangOf(code: string): string {
  return LANGUAGE_BY_CODE.get(code)?.voice ?? code;
}
`;
writeFileSync("src/inference/languages.ts", out);
const noSample = rows.filter((r) => !r.sample).map((r) => r.code);
console.log(`${rows.length} languages -> src/inference/languages.ts`);
console.log(`  native voice: ${rows.filter((r) => !r.voice).length}, donor voice: ${rows.filter((r) => r.voice).length}`);
console.log(`  trained: ${rows.filter((r) => r.trained).length}`);
if (noSample.length) console.log(`  ⚠ no sample text: ${noSample.join(" ")}`);
